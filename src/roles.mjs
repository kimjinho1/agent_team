export function artifactOf(roleKey, stack) {
  const role = ROLE_BY_KEY[roleKey];
  if (!role) return 'output.md';
  const entry = role.stackKey && stack?.[role.stackKey]?.entry;
  return entry || role.defaultArtifact;
}
